#!/usr/bin/env python3
"""Launcher icon (design appIcon): clinic green #2E7D6B background; a cream #F2EBDD bandage roll lying on its side with
a strip running up to the right (two faint pressed-edge lines), its last bit lead orange #F26B1D. Flat, no text.
Writes the adaptive foreground vector + background colour; --png OUT.png renders a 512 px PNG (needs Pillow).
  python3 tools/make_icon.py [--png OUT.png]
"""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
RES = os.path.join(HERE, "..", "app", "src", "main", "res")
BG, CREAM, SHADE, CORE, LEAD = "#2E7D6B", "#F2EBDD", "#D8CDB6", "#B9AA8C", "#F26B1D"
STRIP = [(38, 46), (72, 30), (79, 43), (47, 62)]
TIP = [(66, 32.8), (72, 30), (79, 43), (72.6, 46)]
LINES = [((44, 52), (74, 37.5)), ((45.5, 56.5), (76, 42))]
ROLL = (40, 62, 17)

def _fit(x, y, s=1.18, c=(51, 54.5)):
    return (54 + (x - c[0]) * s, 54 + (y - c[1]) * s)

STRIP = [_fit(*p) for p in STRIP]
TIP = [_fit(*p) for p in TIP]
LINES = [(_fit(*a), _fit(*b)) for a, b in LINES]
ROLL = (*_fit(40, 62), 17 * 1.18)
RINGS = [(12, SHADE), (6.5, CORE)]

def poly(pts): return "M" + " L".join(f"{x:.2f},{y:.2f}" for x, y in pts) + "Z"
def circle(cx, cy, r): return f"M{cx - r:.2f},{cy:.2f} a{r:.2f},{r:.2f} 0 1,0 {2 * r:.2f},0 a{r:.2f},{r:.2f} 0 1,0 {-2 * r:.2f},0Z"
def argb(h): return "#FF" + h[1:].upper()

def vector():
    s = ['<?xml version="1.0" encoding="utf-8"?>', "<!-- generated by tools/make_icon.py (design appIcon): bandage roll + strip, orange lead -->",
         '<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">',
         f'    <path android:fillColor="{argb(CREAM)}" android:pathData="{poly(STRIP)}" />',
         ]
    for a, b in LINES:
        s.append(f'    <path android:strokeColor="{argb(SHADE)}" android:strokeWidth="1.4" android:strokeLineCap="round" android:pathData="M{a[0]:.2f},{a[1]:.2f} L{b[0]:.2f},{b[1]:.2f}" />')
    s.append(f'    <path android:fillColor="{argb(LEAD)}" android:pathData="{poly(TIP)}" />')
    cx, cy, r = ROLL
    s.append(f'    <path android:fillColor="{argb(CREAM)}" android:pathData="{circle(cx, cy, r)}" />')
    s.append(f'    <path android:strokeColor="{argb(SHADE)}" android:strokeWidth="1.6" android:fillColor="#00000000" android:pathData="{circle(cx, cy, 12 * 1.18)}" />')
    s.append(f'    <path android:fillColor="{argb(CORE)}" android:pathData="{circle(cx, cy, 6.5 * 1.18)}" />')
    s.append("</vector>")
    return "\n".join(s) + "\n"

def png(out, size=512):
    from PIL import Image, ImageDraw
    k = size / 108 * 4
    im = Image.new("RGB", (size * 4, size * 4), BG)
    d = ImageDraw.Draw(im)
    P = lambda pts: [(x * k, y * k) for x, y in pts]
    d.polygon(P(STRIP), fill=CREAM)
    for a, b in LINES:
        d.line(P([a, b]), fill=SHADE, width=int(1.4 * k))
    d.polygon(P(TIP), fill=LEAD)
    cx, cy, r = ROLL
    d.ellipse([(cx - r) * k, (cy - r) * k, (cx + r) * k, (cy + r) * k], fill=CREAM)
    d.ellipse([(cx - 14.2) * k, (cy - 14.2) * k, (cx + 14.2) * k, (cy + 14.2) * k], outline=SHADE, width=int(1.6 * k))
    d.ellipse([(cx - 7.7) * k, (cy - 7.7) * k, (cx + 7.7) * k, (cy + 7.7) * k], fill=CORE)
    im.resize((size, size), Image.LANCZOS).save(out)

if __name__ == "__main__":
    open(os.path.join(RES, "drawable", "ic_launcher_foreground.xml"), "w").write(vector())
    open(os.path.join(RES, "values", "colors.xml"), "w").write('<?xml version="1.0" encoding="utf-8"?>\n<resources>\n    <!-- design appIcon 诊室绿 #2E7D6B -->\n    <color name="ic_launcher_background">#FF2E7D6B</color>\n</resources>\n')
    if "--png" in sys.argv:
        png(sys.argv[sys.argv.index("--png") + 1])
    print("icon written")
